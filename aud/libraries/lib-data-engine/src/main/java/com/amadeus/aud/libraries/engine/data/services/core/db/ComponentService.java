package com.amadeus.aud.libraries.engine.data.services.core.db;

import com.amadeus.aud.libraries.common.LogExecutionTime;
import com.amadeus.aud.libraries.engine.data.models.core.internals.Version;
import com.amadeus.aud.libraries.engine.data.repositories.base.ConcurrentRepository;
import com.amadeus.aud.libraries.engine.data.repositories.core.db.ComponentsRepository;
import com.amadeus.aud.libraries.engine.data.services.core.db.base.BaseService;
import com.amadeus.aud.libraries.models.core.db.Component;
import com.amadeus.aud.libraries.models.core.db.Scope;
import com.amadeus.aud.libraries.yaml.models.V1Component;
import com.amadeus.aud.libraries.yaml.models.V1ComponentSpec;
import jakarta.inject.Singleton;
import java.util.List;
import java.util.Objects;

@Singleton
public class ComponentService extends BaseService<Component, V1Component> {

  @Override
  protected ComponentsRepository getRepository(Version version) {
    ComponentsRepository componentsRepository = new ComponentsRepository();
    version.setComponentsRepository(componentsRepository);
    return componentsRepository;
  }

  @LogExecutionTime
  public void init(Version version) {
    ConcurrentRepository<Component> repository =
        init(
            version,
            Component.class,
            V1Component.class,
            (Component component, Scope scope) -> {
              if (scope == null) {
                return;
              }
              scope.addComponent(component);
            });
    if (repository == null || repository.getDataSize() == 0) {
      return;
    }

    initComponentParents(repository);
  }

  // getData().getSpec().getParents() cannot return null today,
  // but we won't know tomorrow since it is an autogenerated class

  private void initComponentParents(ConcurrentRepository<Component> componentsRepository) {
    Component topLevel = componentsRepository.get("TopLevel");
    if (topLevel == null) {
      throw new IllegalStateException("TopLevel component not found");
    }

    Component topLevelContainer = componentsRepository.get("TopLevelContainer");
    if (topLevelContainer == null) {
      throw new IllegalStateException("TopLevelContainer component not found");
    }

    Component topLevelIaas = componentsRepository.get("TopLevelIaaS");

    componentsRepository
        .getData()
        .forEach(
            (String s, Component component) ->
                processComponentParents(
                    component, componentsRepository, topLevel, topLevelContainer, topLevelIaas));
  }

  private void processComponentParents(
      Component component,
      ConcurrentRepository<Component> componentsRepository,
      Component topLevel,
      Component topLevelContainer,
      Component topLevelIaas) {

    V1ComponentSpec spec = component.getData().getSpec();

    if (Boolean.FALSE.equals(spec.getIsTechnical())) {
      linkToTopLevelParents(component, spec, topLevel, topLevelContainer, topLevelIaas);
    }

    linkToExplicitParents(component, spec.getParents(), componentsRepository);
  }

  private void linkToTopLevelParents(
      Component component,
      V1ComponentSpec spec,
      Component topLevel,
      Component topLevelContainer,
      Component topLevelIaas) {

    linkParentChild(component, topLevel);

    if (Boolean.TRUE.equals(spec.getIsContainer())) {
      linkParentChild(component, topLevelContainer);
    }

    if (Boolean.FALSE.equals(spec.getIsContainer())) {
      linkParentChild(component, topLevelIaas);
    }
  }

  private static void linkParentChild(Component child, Component parent) {
    if (parent != null && !Objects.equals(child, parent)) {
      child.addParent(parent);
      parent.addChild(child);
    }
  }

  private void linkToExplicitParents(
      Component component,
      List<String> parentNames,
      ConcurrentRepository<Component> componentsRepository) {

    if (parentNames.isEmpty()) {
      return;
    }

    for (String parentName : parentNames) {
      if (Objects.equals(parentName, component.getName())) {
        continue;
      }

      Component parent = componentsRepository.get(parentName);
      if (parent == null) {
        logModelWarning(
            "Component %s references a non-existing parent %s", component.id(), parentName);
      } else {
        component.addParent(parent);
        parent.addChild(component);
      }
    }
  }
}
